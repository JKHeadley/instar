const REPOSITORY = fileURLToPath(new URL('../../../', import.meta.url));
/** Read immutable source bytes. A symlink may never escape into an agent home. */
export function readAccountsConsoleAsset(asset: Readonly<AccountsConsoleAsset>): Buffer {
  const root = fs.realpathSync(REPOSITORY);
  const filename = fs.realpathSync(path.resolve(root, asset.file));
  if (!filename.startsWith(root + path.sep)) throw new Error('Fixture asset is outside its repository');
  return fs.readFileSync(filename);
}
