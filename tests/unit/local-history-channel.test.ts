import { describe, expect, it } from 'vitest';
import { LocalHistoryChannel } from '../../src/import/LocalHistoryChannel.js';

const scope = { channelId: 'channel-1', machineId: 'machine-1', bootId: 'boot-1', deviceKeyHash: 'device-1' };
const keys = { request: Buffer.alloc(32, 1), response: Buffer.alloc(32, 2) };
function pair() { return [new LocalHistoryChannel(keys, scope, 'client'), new LocalHistoryChannel(keys, scope, 'server')] as const; }
const route = { method: 'POST', path: '/mobile/imported-history/local/library' };

describe('local history sealed channel', () => {
  it('matches the independent Swift CryptoKit wire vector', () => {
    // Generated by tests/fixtures/local-history/channel-vector.swift on macOS.
    const [client] = pair();
    expect(client.sealRequest(Buffer.from('synthetic vector'), route).toString('hex')).toBe(
      '0000000000000001a02ce5bb55939bce0de73a4911b22b873d4b88b014af40c1f9ee79480f38693d');
  });
  it('advances each direction through multiple complete exchanges', () => {
    const [client, server] = pair();
    for (let index = 1; index <= 3; index++) {
      const request = client.sealRequest(Buffer.from(String(index)), route);
      expect(request.readBigUInt64BE(0)).toBe(BigInt(index));
      expect(server.openRequest(request, route).toString()).toBe(String(index));
      const response = server.sealResponse(Buffer.from('reply' + index), route);
      expect(client.openResponse(response, route).toString()).toBe('reply' + index);
    }
  });

  it('authenticates private selectors and allows one exact response per request', () => {
    const [client, server] = pair();
    const record = client.sealRequest(Buffer.from('{"query":"private synthetic words"}'), route);
    expect(record.includes(Buffer.from('private synthetic words'))).toBe(false);
    expect(server.openRequest(record, route).toString()).toContain('private synthetic words');
    const response = server.sealResponse(Buffer.from('private response'), route);
    expect(client.openResponse(response, route).toString()).toBe('private response');
    expect(() => server.sealResponse(Buffer.from('different response'), route)).toThrow();
    expect(() => server.openRequest(record, route)).toThrow();
  });
  it.each(['machineId', 'bootId', 'deviceKeyHash', 'channelId'] as const)('binds %s', field => {
    const [client] = pair();
    const wrong = new LocalHistoryChannel(keys, { ...scope, [field]: 'different' }, 'server');
    expect(() => wrong.openRequest(client.sealRequest(Buffer.from('secret'), route), route)).toThrow();
  });
  it('does not consume a sequence on failed authentication', () => {
    const [client, server] = pair();
    const record = client.sealRequest(Buffer.from('secret'), route);
    const tampered = Buffer.from(record); tampered[tampered.length - 1] ^= 1;
    expect(() => server.openRequest(tampered, route)).toThrow();
    expect(server.openRequest(record, route).toString()).toBe('secret');
  });
  it('binds method/path, rejects reflection, and forbids a second in-flight request', () => {
    const [client, server] = pair();
    const record = client.sealRequest(Buffer.from('secret'), route);
    expect(() => client.sealRequest(Buffer.from('second'), route)).toThrow();
    expect(() => server.openRequest(record, { ...route, path: route.path + '/other' })).toThrow();
    expect(() => server.openResponse(record, route)).toThrow();
    expect(server.openRequest(record, route).toString()).toBe('secret');
  });
  it('pins endpoint roles so the server cannot reuse a client request nonce', () => {
    const [client, server] = pair();
    const request = client.sealRequest(Buffer.from('first'), route);
    server.openRequest(request, route);
    client.openResponse(server.sealResponse(Buffer.from('done'), route), route);
    expect(() => server.sealRequest(Buffer.from('server must not send requests'), route)).toThrow();
    expect(() => client.openRequest(request, route)).toThrow();
    expect(() => client.sealResponse(Buffer.from('client must not send replies'), route)).toThrow();
    expect(() => server.openResponse(request, route)).toThrow();
  });
  it('rejects reflected and tampered response records while preserving the pending response', () => {
    const [client, server] = pair();
    const request = client.sealRequest(Buffer.from('request'), route);
    server.openRequest(request, route);
    expect(() => client.openResponse(request, route)).toThrow();
    const response = server.sealResponse(Buffer.from('response'), route);
    const broken = Buffer.from(response); broken[8] ^= 1;
    expect(() => client.openResponse(broken, route)).toThrow();
    expect(client.openResponse(response, route).toString()).toBe('response');
    expect(() => client.openResponse(response, route)).toThrow();
  });
  it('enforces total wire size and disposal' , () => {
    const [client, server] = pair();
    expect(() => client.sealRequest(Buffer.alloc(1024 * 1024 - 23), route)).toThrow();
    const record = client.sealRequest(Buffer.alloc(1024 * 1024 - 24), route);
    expect(record.length).toBe(1024 * 1024);
    server.dispose();
    expect(() => server.openRequest(record, route)).toThrow();
  });
});
