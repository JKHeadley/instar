export const SPEC_DESIGN_APPROVAL_REQUEST = `the text ASKS the operator (or the team owner) to approve, sign off on, accept or green-light a spec, a design, an architecture or a plan for something to be built, so that their yes lets the build go ahead. Words do not decide it; "here's the design, OK to build?", "ready for your review and approval", "say yes and I start" all count`;
